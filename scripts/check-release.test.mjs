// Negative and positive tests for scripts/check-release.mjs: the release gate must fail on a version
// mismatch and on an empty changelog section, and pass on a real one. Each case builds a small repo
// copy in a temp folder and runs the script on it (the script takes the repo root as its argument).
//
// Run: node --test scripts/check-release.test.mjs
import { test, after } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, copyFileSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const scripts = dirname(fileURLToPath(import.meta.url));
const root = mkdtempSync(join(tmpdir(), "daytrace-check-release-"));
after(() => rmSync(root, { recursive: true, force: true }));

const V = "0.3.0";
const cargoToml = (v) => `[package]\nname = "daytrace"\nversion = "${v}"\nedition = "2021"\n\n[dependencies]\nserde = "1"\n`;
const cargoLock = (v) => `# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "aho-corasick"\nversion = "1.1.3"\n\n[[package]]\nname = "daytrace"\nversion = "${v}"\ndependencies = [\n "serde",\n]\n\n[[package]]\nname = "daytrace-mcp"\nversion = "0.1.0"\n`;
const changelog = (body, { heading = `## ${V}`, crlf = false } = {}) => {
  const text = `# Changelog\n\n${heading}\n\n${body}\n\n## Unreleased\n\n- something unreleased\n`;
  return crlf ? text.replace(/\n/g, "\r\n") : text;
};

// Writes one repo copy and runs the check on it; returns the exit code and the stdout lines.
function run({ pkg = V, conf = V, toml = V, lock = V, log = changelog("### Fixed\n- A crash on start") }) {
  rmSync(root, { recursive: true, force: true });
  for (const d of ["scripts", "src-tauri", "docs"]) mkdirSync(join(root, d), { recursive: true });
  writeFileSync(join(root, "package.json"), JSON.stringify({ name: "daytrace", version: pkg }));
  writeFileSync(join(root, "src-tauri", "tauri.conf.json"), JSON.stringify({ productName: "Daytrace", version: conf }));
  writeFileSync(join(root, "src-tauri", "Cargo.toml"), cargoToml(toml));
  writeFileSync(join(root, "src-tauri", "Cargo.lock"), cargoLock(lock));
  writeFileSync(join(root, "CHANGELOG.md"), log);
  writeFileSync(join(root, "README.md"), "# Daytrace\n\nThere is no published release yet.\n");
  writeFileSync(join(root, "docs", "features.md"), "# Features\n");
  for (const f of ["check-release.mjs", "changelog-section.mjs"]) copyFileSync(join(scripts, f), join(root, "scripts", f));
  const r = spawnSync(process.execPath, [join(root, "scripts", "check-release.mjs"), root], { encoding: "utf8" });
  return { exit: r.status, out: r.stdout.split(/\r?\n/), err: r.stderr };
}

const passes = (name, args) =>
  test(`passes: ${name}`, () => {
    const r = run(args);
    assert.equal(r.exit, 0, r.out.join("\n") + r.err);
    assert.ok(r.out.some((l) => l.startsWith("PASS version:")), r.out.join("\n"));
    assert.ok(r.out.some((l) => l.startsWith("PASS changelog:")), r.out.join("\n"));
  });
const fails = (name, args, line) =>
  test(`fails: ${name}`, () => {
    const r = run(args);
    assert.equal(r.exit, 1, r.out.join("\n") + r.err);
    assert.ok(r.out.some((l) => l.startsWith(line)), `expected a line starting with "${line}" in:\n${r.out.join("\n")}`);
  });

// 1. Version sync: every one of the four files can break it.
passes("the same version everywhere", {});
fails("package.json differs", { pkg: "0.3.1" }, "FAIL version:");
fails("tauri.conf.json differs", { conf: "0.2.9" }, "FAIL version:");
fails("Cargo.toml differs", { toml: "0.3.1" }, "FAIL version:");
fails("Cargo.lock differs", { lock: "0.2.9" }, "FAIL version:");
fails("Cargo.lock has no daytrace package", { lock: cargoLock(V).replace('name = "daytrace"\n', 'name = "daytrase"\n') }, "FAIL version:");
test("a version mismatch names the file", () => {
  const r = run({ lock: "0.2.9" });
  assert.ok(r.out.includes("version src-tauri/Cargo.lock: 0.2.9"), r.out.join("\n"));
});

// 2. Changelog section: the version needs its own heading with real text under it.
passes("real notes under the heading", { log: changelog("### Added\n- Tray icon\n\n### Fixed\n- A crash on start") });
passes("CRLF line endings", { log: changelog("### Fixed\n- A crash on start", { crlf: true }) });
passes("bracketed heading with a date", { log: changelog("- A crash on start", { heading: `## [${V}] - 2026-11-09` }) });
passes("heading with a v prefix", { log: changelog("- A crash on start", { heading: `## v${V}` }) });
passes("note starting with an issue number", { log: changelog("#123 fixed: the tray icon no longer flickers") });
passes("note after a comment on the same line", { log: changelog("<!-- x --> Fixed a crash") });
passes("note after the short <!--> comment", { log: changelog("<!-->\n- A crash on start") });
passes("note after the short <!---> comment", { log: changelog("<!--->\n- A crash on start") });
passes("note with a code span of dashes", { log: changelog("- Use `---` to end the block") });
passes("note that shows <!-- in a code span", { log: changelog("- `<!--` is now kept in notes\n- A crash on start") });
passes("fenced code block with text", { log: changelog("```\ndaytrace --help\n```") });
passes("note inside <details>", { log: changelog("<details><summary>More</summary>\nA crash on start\n</details>") });

fails("no heading for the version", { log: "# Changelog\n\n## 0.2.0\n\n- Old\n\n## Unreleased\n\n- New\n" }, "FAIL changelog: no");
fails("only a subheading", { log: changelog("### Added") }, "FAIL changelog:");
fails("only an HTML comment", { log: changelog("<!-- nothing yet -->") }, "FAIL changelog:");
fails("only a multi-line HTML comment", { log: changelog("<!--\nnothing yet\n-->") }, "FAIL changelog:");
fails("only an unclosed HTML comment", { log: changelog("<!-- todo: write notes") }, "FAIL changelog:");
fails("only the short <!--> comment", { log: changelog("<!-->") }, "FAIL changelog:");
fails("only a [//]: # comment", { log: changelog("[//]: # (write notes)") }, "FAIL changelog:");
fails("only a [//]: <> comment", { log: changelog("[//]: <> (write notes)") }, "FAIL changelog:");
fails("only a [comment]: <> comment", { log: changelog("[comment]: <> (write notes)") }, "FAIL changelog:");
fails("only a link reference definition", { log: changelog("[tray]: https://example.com/tray") }, "FAIL changelog:");
fails("only a thematic break", { log: changelog("---") }, "FAIL changelog:");
fails("only an empty bullet", { log: changelog("- ") }, "FAIL changelog:");
fails("only an empty task item", { log: changelog("- [ ]") }, "FAIL changelog:");
fails("only &nbsp;", { log: changelog("&nbsp;") }, "FAIL changelog:");
fails("only <br>", { log: changelog("<br>") }, "FAIL changelog:");
fails("only an empty fenced block", { log: changelog("```\n```") }, "FAIL changelog:");
fails("only an empty code span", { log: changelog("``") }, "FAIL changelog:");
fails("only a code span holding one space", { log: changelog("` `") }, "FAIL changelog:");
fails("only a code span holding spaces and a tab", { log: changelog("`  \t `") }, "FAIL changelog:");
// Accepted leftover: the gate checks for text, it does not judge it. A placeholder is text.
passes("a placeholder bullet is text", { log: changelog("- TBD") });
fails("subheadings around a comment", { log: changelog("### Added\n<!-- todo -->\n### Fixed") }, "FAIL changelog:");
fails("comment-only section with CRLF", { log: changelog("<!-- nothing yet -->", { crlf: true }) }, "FAIL changelog:");

// The two scripts agree on which section is the version's: both take the first heading that matches.
passes("takes the first section when the version appears twice", {
  log: `# Changelog\n\n## ${V}\n\n- Real note\n\n## ${V}\n\n- Second section with the same version\n`,
});
test("the PASS line counts the lines of the first section", () => {
  const r = run({ log: `# Changelog\n\n## ${V}\n\n- Real note\n\n## ${V}\n\n- Second section with the same version\n` });
  assert.ok(r.out.includes(`PASS changelog: "## ${V}" has 1 lines of release notes`), r.out.join("\n"));
});
